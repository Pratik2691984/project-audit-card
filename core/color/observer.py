@dataclass(frozen=True)
class TristimulusXYZ:
    X: float
    Y: float
    Z: float

def get_cie_1931_2deg_cmf() -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    return (
        np.array(CIE_1931_2DEG_X_BAR, dtype=np.float64),
        np.array(CIE_1931_2DEG_Y_BAR, dtype=np.float64),
        np.array(CIE_1931_2DEG_Z_BAR, dtype=np.float64),
    )

def get_cie_d50_spd() -> np.ndarray:
    return np.array(CIE_D50_SPD_TABLE, dtype=np.float64)

def compute_tristimulus_d50(
    reflectance: np.ndarray,
    cmf_x: np.ndarray,
    cmf_y: np.ndarray,
    cmf_z: np.ndarray,
) -> TristimulusXYZ:
    spd = get_cie_d50_spd()
    delta_wl = float(WAVELENGTH_STEP)
    k = 100.0 / np.sum(spd * cmf_y * delta_wl)
    X = float(k * np.sum(reflectance * spd * cmf_x * delta_wl))
    Y = float(k * np.sum(reflectance * spd * cmf_y * delta_wl))
    Z = float(k * np.sum(reflectance * spd * cmf_z * delta_wl))
    return TristimulusXYZ(X=X, Y=Y, Z=Z)
